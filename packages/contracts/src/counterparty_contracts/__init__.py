"""Public contracts shared by Counterparty Workspace services.

The package is data only: it opens no network, database or file handle, at
import time or later. Three product rules are encoded in the types themselves,
so a caller cannot lose them by accident:

* absence of data never proves absence of risk, so ``missing``,
  ``present_empty``, ``invalid`` and ``restricted`` stay distinct from a real
  zero (:class:`FactValue`);
* an external assessment such as ``zskRiskLevel`` travels as its raw token, and
  an unknown token neither breaks parsing nor becomes a favourable default;
* a reported fact carries at least one resolvable :class:`EvidenceRef`.

Money is a :class:`decimal.Decimal` transported as a plain string, and a source
``$date`` stays an exact instant rather than a calendar day.
"""

